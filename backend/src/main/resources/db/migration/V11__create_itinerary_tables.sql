CREATE TABLE itineraries(

    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    title VARCHAR(150) NOT NULL,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_itineraries_user
       FOREIGN KEY (user_id)
       REFERENCES users(id)
       ON DELETE CASCADE,

    CONSTRAINT chk_itineraries_dates
    CHECK (end_date>start_date)   
);

CREATE TABLE itinerary_days(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    itinerary_id BIGINT NOT NULL,
    day_number INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_itinerary_days_itinerary
    FOREIGN KEY (itinerary_id) REFERENCES itineraries(id) ON DELETE CASCADE,

     CONSTRAINT chk_itinerary_days_number CHECK (day_number>0),

     CONSTRAINT uk_itinerary_days_number UNIQUE (itinerary_id,day_number)
);

CREATE TABLE itinerary_stops(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    itinerary_day_id BIGINT NOT NULL,
    attraction_id BIGINT NOT NULL,
    stop_order INTEGER NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_itinerary_stops_day FOREIGN KEY (itinerary_day_id) REFERENCES itinerary_days(id)
    ON DELETE CASCADE,

    CONSTRAINT fk_itinerary_stops_attraction FOREIGN KEY (attraction_id) REFERENCES attractions(id)
    ON DELETE CASCADE,

    CONSTRAINT chk_itinerary_stops_order CHECK (stop_order > 0),

    CONSTRAINT uk_itinerary_stops_order UNIQUE(itinerary_day_id,stop_order)
);

CREATE INDEX idx_itineraries_user_id ON itineraries (user_id);

CREATE INDEX idx_itinerary_stops_attraction_id
    ON itinerary_stops(attraction_id);