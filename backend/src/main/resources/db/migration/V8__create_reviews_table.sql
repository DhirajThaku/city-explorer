CREATE TABLE reviews(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    attraction_id BIGINT NOT NULL,
    rating INTEGER NOT NULL,
    comment TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_reviews_user FOREIGN KEY(user_id) REFERENCES users(id)
    ON DELETE CASCADE,

    CONSTRAINT fk_reviews_attraction FOREIGN KEY(attraction_id) REFERENCES attractions(id) 
    ON DELETE CASCADE,

    CONSTRAINT uk_reviews_user_attraction UNIQUE(user_id,attraction_id),

    CONSTRAINT chk_reviews_rating CHECK (rating BETWEEN 1 AND 5),

    CONSTRAINT chk_reviews_comment_length CHECK (LENGTH(TRIM(comment)) BETWEEN 1 AND 2000)
)